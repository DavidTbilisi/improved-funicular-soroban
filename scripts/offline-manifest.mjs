// ============================================================================
// The precache list — every file the app needs to boot with no network.
//
// This repo has no build step, which is a feature everywhere else and a problem
// here: a service worker has to be handed an explicit list of files, and a
// hand-maintained list of ~60 ES modules drifts the moment anyone adds a page.
// Worse, it drifts SILENTLY — the app keeps working online and only fails on
// the train, which is the one place nobody is testing.
//
// So the list is DERIVED. This walks each root .html for its stylesheet and its
// entry module, then follows the static `import` graph from there, and writes
// offline-manifest.json. It is a maintenance script rather than a build step:
// the checked-in JSON is what ships, and test/offlineManifest.test.js recomputes
// the graph and fails if the two have parted company, naming the command to fix
// it. Nothing at runtime runs this.
//
// Paths are REPO-RELATIVE with no leading slash, on purpose: the app is served
// from the domain root locally and from /improved-funicular-soroban/ on GitHub
// Pages, and a relative URL resolves correctly against the service worker's own
// scope in both. An absolute '/styles.css' would precache the wrong origin path
// on Pages and quietly cache nothing.
//
// Zero dependencies: node's own fs and a regex. The import syntax in this repo
// is plain static `import … from '…'`, which a regex can read exactly; if that
// ever stops being true, the test is what will say so.
// ============================================================================
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, normalize, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = normalize(join(dirname(fileURLToPath(import.meta.url)), '..'));
export const MANIFEST_PATH = join(ROOT, 'offline-manifest.json');

const rel = p => relative(ROOT, p).split('\\').join('/');
const read = p => readFileSync(join(ROOT, p), 'utf8');

// Every page shell at the repo root. Order is alphabetical, which is also the
// order they end up cached in — cosmetic, but it keeps diffs readable.
export const pages = () => readdirSync(ROOT).filter(f => f.endsWith('.html')).sort();

const STYLE_RE = /<link[^>]+rel=["']stylesheet["'][^>]+href=["']([^"']+)["']/g;
const MODULE_RE = /<script[^>]+type=["']module["'][^>]+src=["']([^"']+)["']/g;
// `import x from 'y'`, `import 'y'`, `export … from 'y'` — the three static
// forms. Dynamic import() is deliberately NOT matched: a dynamically imported
// module is by definition not needed to boot, and precaching it would be a
// guess about a code path this script cannot see.
const IMPORT_RE = /(?:^|[\s;}])(?:import|export)\s+(?:[\s\S]*?\sfrom\s+)?["']([^"']+)["']/g;

const matches = (src, re) => [...src.matchAll(re)].map(m => m[1]);

// Resolve a specifier written inside `fromFile` to a repo-relative path.
function resolveFrom(fromFile, spec) {
  if (/^[a-z]+:/i.test(spec) || spec.startsWith('//')) return null;   // external
  return rel(join(ROOT, dirname(fromFile), spec));
}

/**
 * Every file needed to boot every page, sorted. Modules are followed
 * transitively; anything outside the repo or non-relative is skipped.
 */
export function collectAssets() {
  const assets = new Set();
  const queue = [];

  for (const page of pages()) {
    assets.add(page);
    const html = read(page);
    for (const href of matches(html, STYLE_RE)) {
      const p = resolveFrom(page, href);
      if (p) assets.add(p);
    }
    for (const src of matches(html, MODULE_RE)) {
      const p = resolveFrom(page, src);
      if (p) { assets.add(p); queue.push(p); }
    }
  }

  const seen = new Set(queue);
  while (queue.length) {
    const file = queue.shift();
    let src;
    try { src = read(file); } catch { continue; }        // a missing import is the smoke test's business
    for (const spec of matches(src, IMPORT_RE)) {
      const p = resolveFrom(file, spec);
      if (!p || seen.has(p) || p.startsWith('..')) continue;
      seen.add(p);
      assets.add(p);
      queue.push(p);
    }
  }

  // The web app manifest and its icons are not reachable from any import graph,
  // but a browser that cannot fetch them offline shows the install prompt's
  // fallback icon on an installed app. Cheap to include, ugly to omit.
  for (const extra of ['manifest.webmanifest', 'icons/soroban-192.png', 'icons/soroban-512.png']) {
    try { read(extra); assets.add(extra); } catch { /* not present yet */ }
  }

  return [...assets].sort();
}

export const buildManifest = () => ({
  note: 'Generated by scripts/offline-manifest.mjs — run `npm run offline:manifest` after adding a page or a module.',
  assets: collectAssets(),
});

// Run directly to rewrite the file.
if (process.argv[1] && normalize(process.argv[1]) === normalize(fileURLToPath(import.meta.url))) {
  const manifest = buildManifest();
  writeFileSync(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`offline-manifest.json — ${manifest.assets.length} files`);
}
